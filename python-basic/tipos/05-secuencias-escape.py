# Ejemplo de uso de secuencias de escape en cadenas de texto
# Secuencias de escape permiten incluir caracteres especiales en cadenas de texto
# \n es un salto de línea
# \t es una tabulación
# \\ es una barra invertida
# \" es una comilla doble
# \n\t\\\" son ejemplos de secuencias de escape
# \n\t\\\" es un ejemplo de secuencia de escape que incluye salto de línea, tabulación y comilla doble

curso = "Ultimate \"Python\""
print(curso)
